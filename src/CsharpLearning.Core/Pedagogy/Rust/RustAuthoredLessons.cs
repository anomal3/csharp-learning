fn найти(список: &[i32], цель: i32) -> Option<usize> {
    for (i, &x) in список.iter().enumerate() {
        if x == цель {
            return Some(i);
        }
    }
    None
}

fn main() {
    let числа = [10, 20, 30];
    match найти(&числа, 20) {
        Some(i) => println!("нашли на месте {}", i),
        None => println!("не нашли"),
    }
    match найти(&числа, 99) {
        Some(i) => println!("нашли на месте {}", i),
        None => println!("не нашли"),
