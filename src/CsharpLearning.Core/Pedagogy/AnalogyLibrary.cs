/// <summary>Определяет, к каким концепциям относится урок, и собирает пояснения.</summary>
public static class ExplanationEngine
{
    static readonly Regex[] HeadingRe = { new(@"<h([2-4])[^>]*>(.*?)</h\1>", RegexOptions.IgnoreCase | RegexOptions.Singleline) };

    public static List<AnalogyLibrary.Analogy> Match(string lessonTitle, string bodyText)
    {
        var haystack = (lessonTitle + "\n" + bodyText).ToLowerInvariant();
        var picked = new List<AnalogyLibrary.Analogy>();
        var seen = new HashSet<string>();

        foreach (var a in AnalogyLibrary.All)
        {
            int score = 0;
            foreach (var kw in a.Keywords)
            {
                if (haystack.Contains(kw.ToLowerInvariant())) score += lessonTitle.ToLowerInvariant().Contains(kw.ToLowerInvariant()) ? 4 : 1;
            }
            if (score >= 2 && seen.Add(a.Concept)) picked.Add(a);
        }
        return picked.OrderBy(a => lessonTitle.ToLowerInvariant().Contains(a.Concept.ToLowerInvariant()) ? 0 : 1).Take(4).ToList();
    }
}
