/// <summary>
/// Авторские вводные уроки: тот самый «нулевой уровень», которого нет в учебнике metanit.
/// Тут объясняется не синтаксис, а мышление: что такое программа, зачем типы, как читать ошибки.
/// Примеры кода — самодостаточные и с предсказуемым выводом: из них строятся вопросы «что выведет».
