    public sealed record Authored(string Slug, string Title, List<ContentBlock> Blocks);

    sealed class B
    {
        readonly List<ContentBlock> _blocks = new();
        public B H(string t) => Add(BlockKind.Heading, t);
        public B P(string t) => Add(BlockKind.Paragraph, t);
        public B L(params string[] items) => Add(BlockKind.List, string.Join("\n", items.Select(i => "• " + i)));
        public B T(string t) => Add(BlockKind.Table, t.Trim('\n'));
        public B C(string code)
        {
            var c = code.Trim('\n');
            _blocks.Add(new ContentBlock { Index = _blocks.Count, Kind = BlockKind.Code, Code = c, Text = c });
            return this;
        }

        B Add(BlockKind k, string t)
        {
            _blocks.Add(new ContentBlock { Index = _blocks.Count, Kind = k, Text = t });
            return this;
        }

        public List<ContentBlock> Done() => _blocks;
    }

    public static IReadOnlyList<Authored> All { get; } = Build();

    static List<Authored> Build() => new()
    {
        Program(), HowRuns(), FirstProgram(), Variables(), Types(), Errors(), Tools(),
    };

